import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { featuredProjects, profile, translations } from '../resume/locales/translations.js';

const languages = { zh: 'zh-CN', en: 'en', ja: 'ja' };
function leaves(value, prefix = '') {
  return Object.entries(value).flatMap(([key, item]) => {
    const location = prefix ? `${prefix}.${key}` : key;
    if (typeof item === 'string') {
      if (!item.trim()) throw new Error(`Empty resume copy: ${location}`);
      return [location];
    }
    if (!item || typeof item !== 'object') throw new Error(`Invalid resume copy: ${location}`);
    return leaves(item, location);
  });
}
export function validateTranslations(dictionaries = translations) {
  if (!dictionaries.zh) throw new Error('Missing resume language: zh');
  const expected = leaves(dictionaries.zh).sort();
  const required = 'title description nav.home nav.about nav.contact nav.portfolio nav.back ui.resume ui.navigation ui.menu ui.language ui.skip ui.print ui.portfolioPrint home.name home.role projects.title projects.details projects.all contact.title'.split(' ');
  for (const language of Object.keys(languages)) {
    const dictionary = dictionaries[language];
    if (!dictionary) throw new Error(`Missing resume language: ${language}`);
    if (JSON.stringify(expected) !== JSON.stringify(leaves(dictionary).sort())) throw new Error(`Incomplete resume language: ${language}`);
    for (const key of required) {
      const value = key.split('.').reduce((item, part) => item?.[part], dictionary);
      if (typeof value !== 'string' || !value.trim()) throw new Error(`Missing resume field: ${language}.${key}`);
    }
    if (!Array.isArray(dictionary.projects.items) || dictionary.projects.items.length !== featuredProjects.length) throw new Error(`Incomplete project selection: ${language}`);
    for (const item of dictionary.projects.items) {
      if (typeof item.name !== 'string' || typeof item.title !== 'string' || !Array.isArray(item.bullets) || item.bullets.length !== 2) throw new Error(`Incomplete project entry: ${language}`);
    }
  }
}
export function renderResume(language = 'zh', dictionaries = translations) {
  validateTranslations(dictionaries);
  const dictionary = dictionaries[language];
  if (!dictionary || !languages[language]) throw new Error(`Unsupported resume language: ${language}`);
  const escape = value => String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;').replaceAll("'", '&#39;');
  const get = key => key.split('.').reduce((value, part) => value[part], dictionary);
  const text = (tag, key, attributes = '') => `<${tag} data-i18n="${key}"${attributes ? ' ' + attributes : ''}>${escape(get(key))}</${tag}>`;
  const nav = ['home', 'about', 'contact'].map(id => text('a', `nav.${id}`, `href="#${id}"${id === 'home' ? ' aria-current="location"' : ''}`)).concat(text('a', 'nav.portfolio', 'href="../project-show/" class="portfolio-link"')).join('\n        ');
  const projects = featuredProjects.map((project, index) => `<article class="project-entry" data-project="${escape(project.id)}">
        <div class="project-heading"><h3>${text('span', `projects.items.${index}.name`, 'class="project-name"')}${text('span', `projects.items.${index}.title`, 'class="project-type"')}</h3>${project.href ? text('a', 'projects.details', `class="project-link" href="${escape(project.href)}"${project.href.startsWith('https://') ? ' target="_blank" rel="noopener noreferrer"' : ''}`) : ''}</div>
        <p class="project-stack">${escape(project.stack)}</p>
        <ul class="project-bullets">${dictionary.projects.items[index].bullets.map((_, bullet) => text('li', `projects.items.${index}.bullets.${bullet}`)).join('')}</ul>
      </article>`).join('\n      ');
  return `<!DOCTYPE html>
<!-- Generated by scripts/render-resume.mjs. Edit resume/locales/translations.js instead. -->
<html lang="${languages[language]}">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title data-i18n="title">${escape(dictionary.title)}</title>
  <meta name="description" data-i18n-content="description" content="${escape(dictionary.description)}">
  <meta name="theme-color" content="#0f172a">
  <meta property="og:title" data-i18n-content="title" content="${escape(dictionary.title)}">
  <meta property="og:description" data-i18n-content="description" content="${escape(dictionary.description)}">
  <meta property="og:type" content="profile">
  <meta property="og:url" content="https://brez.top/resume/">
  <link rel="canonical" href="https://brez.top/resume/">
  <link rel="icon" href="../apple-touch-icon.png" type="image/png">
  <link rel="stylesheet" href="./css/resume.css">
  <script type="module" src="./js/app.js"></script>
</head>
<body>
  ${text('a', 'ui.skip', 'class="skip-link" href="#home"')}
  <header class="site-header">
    <div class="header-inner wrap">
      <a class="park-return" href="../"><span data-i18n="nav.back">${escape(dictionary.nav.back)}</span><small>BREEZE / RESUME</small></a>
      <nav class="desktop-nav" aria-label="${escape(dictionary.ui.navigation)}" data-i18n-label="ui.navigation">
        ${nav}
      </nav>
      <div class="language-controls" role="group" aria-label="${escape(dictionary.ui.language)}" data-i18n-label="ui.language" hidden>
        <button type="button" class="lang-btn" data-lang="zh" lang="zh-CN" aria-pressed="${language === 'zh'}">中文</button>
        <button type="button" class="lang-btn" data-lang="en" lang="en" aria-pressed="${language === 'en'}">English</button>
        <button type="button" class="lang-btn" data-lang="ja" lang="ja" aria-pressed="${language === 'ja'}">日本語</button>
      </div>
      <button type="button" class="menu-toggle" aria-controls="mobile-menu" aria-expanded="false" aria-label="${escape(dictionary.ui.menu)}" data-i18n-label="ui.menu" hidden><span aria-hidden="true">☰</span></button>
    </div>
    <nav class="mobile-menu wrap" id="mobile-menu" aria-label="${escape(dictionary.ui.navigation)}" data-i18n-label="ui.navigation" hidden inert>
        ${nav}
    </nav>
  </header>
  <main class="wrap">
    <section id="home" class="resume-section hero" aria-labelledby="hero-name" tabindex="-1">
      <div>${text('p', 'ui.resume', 'class="eyebrow"')}${text('h1', 'home.name', 'id="hero-name"')}${text('p', 'home.role', 'class="hero-role"')}</div>
      <button type="button" class="print-button" hidden><span data-i18n="ui.print">${escape(dictionary.ui.print)}</span></button>
      <p class="print-portfolio">${text('span', 'ui.portfolioPrint')} · ${escape(profile.portfolio)}</p>
    </section>
    <section id="about" class="resume-section projects" aria-labelledby="about-title" tabindex="-1">
      <span id="future" class="legacy-anchor" tabindex="-1"></span>
      <div class="section-heading">${text('h2', 'projects.title', 'id="about-title"')}${text('a', 'projects.all', 'href="../project-show/" class="portfolio-link"')}</div>
      ${projects}
    </section>
  </main>
  <footer id="contact" class="site-footer wrap" aria-labelledby="contact-title" tabindex="-1">
    ${text('h2', 'contact.title', 'id="contact-title"')}
    <a href="mailto:${escape(profile.email)}">${escape(profile.email)}</a>
    <a href="https://github.com/${escape(encodeURIComponent(profile.github))}" target="_blank" rel="noopener noreferrer">github.com/${escape(profile.github)}</a>
  </footer>
</body>
</html>
`;
}
export function checkResumeHtml(actual, expected = renderResume()) {
  if (actual.replace(/\r\n/g, '\n') !== expected) throw new Error('Resume HTML is stale; run node scripts/render-resume.mjs');
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const target = new URL('../resume/index.html', import.meta.url);
  const html = renderResume();
  if (process.argv.includes('--check')) {
    checkResumeHtml(await readFile(target, 'utf8'), html);
    console.log('PASS: resume HTML and all three languages match their content source');
  } else {
    await writeFile(target, html);
    console.log('Updated resume/index.html from resume/locales/translations.js');
  }
}
